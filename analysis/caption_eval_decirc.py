#!/usr/bin/env python3
"""
A1 — De-circularized caption evaluation.

Re-scores the 100-snippet caption benchmark with TWO non-Gemini audio-LLM judges
(Voxtral-Small-24B, open-weight; GPT-Audio-1.5, proprietary), to check that
Music-Whisper's standing is not an artifact of same-family (Gemini teacher ->
Gemini judge) evaluation. The paper's main caption table (tab:model-rankings) is
judged by Gemini 3.1 Pro; this is the independent-judge cross-check it asks for.

Input : analysis/input/caption_eval_decirc/caption_eval_decirc_first100.json
        (per-model, per-judge, per-clip holistic 1-5 scores on the first 100 of
         the 200 held-out Suno snippets — the same 100 used in the paper table.)
Output: analysis/output/caption_eval_decirc.csv
        analysis/output/caption_eval_decirc_table.tex

Run:    cd analysis && python caption_eval_decirc.py        (stdlib only)
"""
import json, os, csv

HERE = os.path.dirname(os.path.abspath(__file__))
IN = os.path.join(HERE, "input", "caption_eval_decirc", "caption_eval_decirc_first100.json")
OUT_CSV = os.path.join(HERE, "output", "caption_eval_decirc.csv")
OUT_TEX = os.path.join(HERE, "output", "caption_eval_decirc_table.tex")

data = json.load(open(IN))
MW = 0.242  # Music-Whisper params (B)

rows = []
for mk, e in data["models"].items():
    vx = e["per_judge"]["voxtral"]["mean"]
    gp = e["per_judge"]["gpt_audio"]["mean"]
    avg = e["nongemini_avg"]
    ratio = (e["params_B"] / MW) if e["params_B"] else None
    rows.append(dict(model=e["display"], type=e["type"], params_B=e["params_B"],
                     size_ratio=ratio, voxtral=vx, gpt_audio=gp, nongemini_avg=avg,
                     n_voxtral=e["per_judge"]["voxtral"]["n"], n_gpt_audio=e["per_judge"]["gpt_audio"]["n"]))
rows.sort(key=lambda r: r["nongemini_avg"], reverse=True)

os.makedirs(os.path.dirname(OUT_CSV), exist_ok=True)
with open(OUT_CSV, "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
    w.writeheader(); w.writerows(rows)
print("wrote", OUT_CSV)

def fp(p):  # params pretty
    return "\\textit{closed}" if p is None else (f"{int(p*1000)}M" if p < 1 else f"{p:.1f}B")
def fr(r):
    return "--" if r is None else (f"{r:.0f}$\\times$")

lines = [
 "% ─── Generated by analysis/caption_eval_decirc.py — do not edit manually ───",
 "% Requires: booktabs",
 "\\begin{table}[t]", "\\centering",
 ("\\caption{Caption evaluation by two non-Gemini judges. The same 100 held-out Suno snippets as "
  "Table~\\ref{tab:model-rankings}, re-scored by Voxtral-Small-24B (open-weight) and GPT-Audio-1.5 "
  "(proprietary) on a single holistic 1--5 caption-quality scale instead of the Coverage/Accuracy pair; "
  "\\emph{Avg.} is the mean of the two judges. The run covers seven captioners, including "
  "MOSS-Audio-4B-Thinking, which was not part of the Gemini-judged run. GPT-Audio-1.5 is also one of "
  "the judges, so its own row is self-scored and shown for reference only. Paired bootstrap intervals "
  "for the differences to Music~Whisper are in Table~\\ref{tab:caption-bootstrap}.}"),
 "\\label{tab:caption-decirc}", "\\small",
 "\\begin{tabular}{llrrrr}", "\\toprule",
 "\\textbf{Model} & \\textbf{Type} & \\textbf{Params} & \\textbf{Voxtral} & \\textbf{GPT-Audio} & \\textbf{Avg.} \\\\",
 "\\midrule",
]
for r in rows:
    name = f"\\textbf{{{r['model']}}}" if "ours" in r["model"] else r["model"]
    typ = "Open" if r["type"] == "open" else "Closed"
    avg = f"\\textbf{{{r['nongemini_avg']:.2f}}}" if "ours" in r["model"] else f"{r['nongemini_avg']:.2f}"
    lines.append(f"  {name} & {typ} & {fp(r['params_B'])} & {r['voxtral']:.2f} & {r['gpt_audio']:.2f} & {avg} \\\\")
lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
open(OUT_TEX, "w").write("\n".join(lines))
print("wrote", OUT_TEX)

# console summary
mw = next(r for r in rows if "ours" in r["model"])
beaten = [r["model"] for r in rows if r["type"] == "open" and r["size_ratio"] and r["size_ratio"] >= 30 and r["nongemini_avg"] < mw["nongemini_avg"]]
print(f"\nMusic Whisper non-Gemini avg = {mw['nongemini_avg']:.2f} (Voxtral {mw['voxtral']:.2f}, GPT-Audio {mw['gpt_audio']:.2f})")
print("Point estimate above (>=30x larger):", ", ".join(beaten))
print("Point estimates only; significance is tested in caption_eval_bootstrap.py "
      "(MOSS-Audio 8B-Thinking is a statistical tie).")
