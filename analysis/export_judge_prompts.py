"""Export the benchmark prompts from model_eval.py without importing the runner.

Run from the repository root: python3 analysis/export_judge_prompts.py
The plain-text exports preserve the base strings, including the user prompt's
trailing newline. The TeX export is included in the manuscript and flattened
by the arXiv builder. Model-specific reasoning wrappers are described there.
"""

from __future__ import annotations

import ast
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"ALLOWED_AI_ASPECTS", "SYSTEM_PROMPT", "USER_INSTRUCTIONS"}


def extract_prompts(source: str) -> dict[str, object]:
    values: dict[str, object] = {}
    for node in ast.parse(source).body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name) or target.id not in NAMES:
            continue
        if isinstance(node.value, ast.JoinedStr):
            parts = []
            for part in node.value.values:
                if isinstance(part, ast.Constant) and isinstance(part.value, str):
                    parts.append(part.value)
                elif (
                    isinstance(part, ast.FormattedValue)
                    and isinstance(part.value, ast.Name)
                    and part.value.id == "ALLOWED_AI_ASPECTS"
                    and part.conversion == -1
                    and part.format_spec is None
                ):
                    parts.append(str(values[part.value.id]))
                else:
                    raise ValueError("Unexpected expression in the prompt f-string")
            values[target.id] = "".join(parts)
        else:
            values[target.id] = ast.literal_eval(node.value)
    if values.keys() != NAMES:
        raise ValueError(f"Missing prompt constants: {NAMES - values.keys()}")
    return values


def main() -> None:
    prompts = extract_prompts((HERE / "model_eval.py").read_text(encoding="utf-8"))
    destination = HERE / "prompts"
    destination.mkdir(exist_ok=True)
    blocks = []
    for kind, name in (("system", "SYSTEM_PROMPT"), ("user", "USER_INSTRUCTIONS")):
        text = prompts[name]
        if not isinstance(text, str):
            raise ValueError(f"{name} must be a string")
        (destination / f"benchmark_judge_{kind}.txt").write_text(text, encoding="utf-8")
        blocks.append(
            "\\noindent\\textbf{" + kind.capitalize() + " prompt.}\n"
            + "\\begin{Verbatim}[fontsize=\\scriptsize,breaklines=true,breakanywhere=true]\n"
            + text.rstrip("\n") + "\n\\end{Verbatim}\n"
        )
    output = HERE / "output" / "benchmark_judge_prompts.tex"
    output.write_text(
        "% Generated by analysis/export_judge_prompts.py from model_eval.py.\n"
        + "\n".join(blocks), encoding="utf-8"
    )
    print(f"Exported system and user prompts to {destination} and {output}")


if __name__ == "__main__":
    main()
