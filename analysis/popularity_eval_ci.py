"""
A8 (partial) — Confidence intervals for the Music-Popularity held-out metrics.

Addresses reviewer zY8i-W3 ("evaluations are performed on roughly 100-200
data ... hard to determine whether the model performance can generalize").

The per-track held-out predictions are not in this repository, so a bootstrap
is not possible here. The reported correlations and n are enough for Fisher-z
intervals, which assume approximate bivariate normality. That assumption is
reasonable for the log1p-transformed targets and is NOT reasonable for the
raw, heavy-tailed counts, so intervals are given for the log-scale Pearson r
only. A bootstrap over the per-track predictions would replace these.

Reported metrics (source: laion/music-popularity model card and
laion-tunes-updated-blog.md, "Evaluation on 200 Held-Out Tracks"; the held-out
set is 200 tracks stratified by play-count bucket, 50 per bucket).

Outputs
  output/popularity_eval_table.tex

Run:  .venv/bin/python popularity_eval_ci.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy import stats

OUTPUT = Path(__file__).parent / "output"
N_HELDOUT = 200
REPORTED = {
    # target: (Pearson r raw, Pearson r on log1p, MAE on log1p)
    "Play count": (0.145, 0.414, 2.981),
    "Upvote count": (0.102, 0.413, 1.923),
}


def fisher_ci(r: float, n: int, level: float = 0.95) -> tuple[float, float]:
    z, se = np.arctanh(r), 1.0 / np.sqrt(n - 3)
    q = stats.norm.ppf(0.5 + level / 2)
    return float(np.tanh(z - q * se)), float(np.tanh(z + q * se))


def main() -> None:
    lines = [
        "% Generated by analysis/popularity_eval_ci.py -- do not edit manually",
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"\textbf{Target} & \textbf{Pearson $r$} & \textbf{Log-Pearson $r$} & \textbf{95\% CI (log)} & \textbf{Log MAE} \\",
        r"\midrule",
    ]
    for target, (r_raw, r_log, mae) in REPORTED.items():
        lo, hi = fisher_ci(r_log, N_HELDOUT)
        print(f"{target:13s} log-Pearson {r_log:.3f}  95% CI [{lo:.2f}, {hi:.2f}]  (n={N_HELDOUT})")
        lines.append(f"{target} & {r_raw:.3f} & {r_log:.3f} & $[{lo:.2f}, {hi:.2f}]$ & {mae:.3f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUTPUT.mkdir(exist_ok=True)
    (OUTPUT / "popularity_eval_table.tex").write_text("\n".join(lines) + "\n")
    print("Wrote output/popularity_eval_table.tex")


if __name__ == "__main__":
    main()
